import { DataAttribution } from '@/components/DataAttribution';
import { EnergyExplorer } from '@/components/energy-sources/EnergyExplorer';
import { EnergyKeyFigures } from '@/components/energy-sources/EnergyKeyFigures';
import { JsonLd } from '@/components/JsonLd';
import { OriginCredit } from '@/components/OriginCredit';
import { buildEnergyDatasetJsonLd } from '@/lib/energyStructuredData';
import { siteUrl } from '@/lib/siteUrl';
import { ECO_CATEGORIES } from '@eco-metrics/shared';
import type { ApiResponseMeta, EnergySourcesData } from '@eco-metrics/shared';

interface EnergySourcesContentProps {
  data: { data: EnergySourcesData; meta: ApiResponseMeta };
}

export function EnergySourcesContent({ data: { data, meta } }: EnergySourcesContentProps) {
  const jsonLd = buildEnergyDatasetJsonLd({
    data,
    meta,
    pageUrl: `${siteUrl()}/${ECO_CATEGORIES.ENERGY_SOURCES}/`,
    dataSourcesUrl: `${siteUrl()}/data-sources/`,
  });

  return (
    <div className="w-full max-w-4xl px-4 pb-12">
      <JsonLd data={jsonLd} />
      <p className="mb-6 text-center text-fg-secondary">
        Where does a country&rsquo;s electricity come from? Explore how much is generated from coal,
        gas, oil, nuclear, hydro, wind, solar and bioenergy since {data.startYear}.
      </p>

      <div className="mb-8 rounded-2xl bg-well px-5 py-5 text-center sm:px-8">
        <EnergyKeyFigures data={data} />
      </div>

      <EnergyExplorer data={data} />

      <p className="mt-6 text-sm text-fg-muted" data-testid="energy-methodology">
        This page covers electricity generation only, not total (primary) energy, so the share of
        renewables in all energy use (heating, transport, industry) is lower than their share of
        electricity. Shares are each source&rsquo;s part of the electricity generated by the eight
        sources shown, computed by this site from the generation values. Bioenergy &amp; other
        renewables is the sum of bioenergy and other renewables, which include geothermal, wave and
        tidal; this sum is a change made by this site to the provider&rsquo;s series. The data
        starts in {data.startYear}. A blank value means the source reported no generation.
      </p>

      <DataAttribution
        testId="energy-attribution"
        meta={meta}
        extra={<OriginCredit origin={data.origin} testId="energy-origin" />}
      />
    </div>
  );
}
